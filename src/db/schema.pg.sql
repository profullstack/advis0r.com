-- Full-text search over transcript segments. SQLite uses an FTS5 virtual table
-- (schema.sql); here it is a plain table with a generated tsvector column and a
-- GIN index. Inserts are identical; the match predicate lives in src/db/fts.ts.
create table if not exists segments_fts (
  id            bigint generated by default as identity primary key,
  text          text NOT NULL,
  speaker       text,
  ticker        text,
  segment_id    text,
  transcript_id text,
  event_date    text,
  search        tsvector generated always as (
                  to_tsvector('english', coalesce(text, '') || ' ' || coalesce(speaker, '') || ' ' || coalesce(ticker, ''))
                ) stored
);

CREATE INDEX IF NOT EXISTS idx_segments_fts_search ON segments_fts USING gin (search);

CREATE INDEX IF NOT EXISTS idx_segments_fts_segment ON segments_fts(segment_id);

