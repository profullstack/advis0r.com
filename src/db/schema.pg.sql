-- transcript-search schema, Postgres edition.
-- Generated from schema.sql with `npx libsql-pg convert-schema`, then reviewed by hand:
-- the FTS5 virtual table became a real table with a generated tsvector column.
-- Applied by migrate() in src/db/index.ts when DATABASE_URL is postgres://; keep the
-- two files in step. Types: INTEGER -> bigint, REAL -> double precision, TEXT stays text.

